-- Hosted shape of the tables the Companion context reads, as observed
-- read-only on 2026-10-25 (row-level security flags and policies from the
-- parent's hosted-access export). Probe fixture only: columns the reads do not
-- use are left out. Policies are copied as written on hosted.

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text,
  username text
);
alter table public.users enable row level security;
create policy "users read own" on public.users for select to authenticated using (auth.uid() = id);
create function public.probe_handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.users (id) values (new.id) on conflict do nothing;
  return new;
end $$;
create trigger probe_on_auth_user_created after insert on auth.users
  for each row execute function public.probe_handle_new_user();

create table public.user_onboarding_profiles (
  id uuid primary key references public.users(id) on delete cascade,
  persona text,
  arrival_date date,
  city text,
  province text,
  stage integer,
  goals text[],
  learning_interests text[],
  updated_at timestamptz not null default now()
);
alter table public.user_onboarding_profiles enable row level security;
create policy "profile select own" on public.user_onboarding_profiles for select using (auth.uid() = id);
create policy "profile insert own" on public.user_onboarding_profiles for insert with check (auth.uid() = id);
create policy "profile update own" on public.user_onboarding_profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "profile delete own" on public.user_onboarding_profiles for delete using (auth.uid() = id);

create table public.user_tasks (
  user_task_id integer generated by default as identity primary key,
  user_id uuid references public.users(id) on delete cascade,
  task_id integer,
  completed boolean default false,
  completed_at timestamp without time zone,
  sanity_checklist_id text,
  created_at timestamptz not null default now(),
  dismissed_at timestamptz,
  constraint user_tasks_user_sanity_checklist_id_key unique (user_id, sanity_checklist_id)
);
alter table public.user_tasks enable row level security;
-- Hosted has NO delete policy on user_tasks (observed).
create policy "Users can view own tasks" on public.user_tasks
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users can insert own tasks" on public.user_tasks
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users can update own tasks" on public.user_tasks
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

