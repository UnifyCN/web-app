create table public.conversations (
  id integer generated by default as identity primary key,
  conversation_identifier uuid not null unique default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  title text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  source text,
  lesson_id text
);
alter table public.conversations enable row level security;
create policy "conv select" on public.conversations for select to authenticated using ((select auth.uid()) = user_id);
create policy "conv insert" on public.conversations for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "conv update" on public.conversations for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "conv delete" on public.conversations for delete to authenticated using ((select auth.uid()) = user_id);

create table public.messages (
  id integer generated by default as identity primary key,
  conversation_id integer references public.conversations(id) on delete cascade,
  role text,
  content text,
  sources jsonb,
  created_at timestamptz not null default now(),
  suggested_next_steps jsonb
);
alter table public.messages enable row level security;
create policy "messages insert" on public.messages for insert to authenticated with check (
  conversation_id in (select conversations.id from public.conversations where conversations.user_id = (select auth.uid())));
create policy "messages select" on public.messages for select to authenticated using (
  conversation_id in (select conversations.id from public.conversations where conversations.user_id = (select auth.uid())));

